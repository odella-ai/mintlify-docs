// Keep static, no-JavaScript channel artwork in sync with its shared MDX sources.
// Emit Mintlify-compatible div/span artwork instead of unsupported raw figures,
// and disable logo lightboxes so clicking a channel logo follows its guide link.
// Static markup keeps logos and navigation present without site JavaScript.
// node scripts/sync-channel-branding.mjs [--write]
import assert from 'node:assert/strict';
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const write = process.argv.includes('--write');
const start = '{/* channel-branding:start — generated by scripts/sync-channel-branding.mjs */}';
const end = '{/* channel-branding:end */}';
const jobs = (await readdir(join(root, 'workforce/channels'))).filter((file) => file.endsWith('.mdx')).map((file) => ({
  page: 'workforce/channels/' + file,
  source: 'snippets/channel-heroes/' + (file === 'meetings.mdx' ? 'google-meet.mdx' : file),
  component: 'ChannelHero',
}));
for (const page of ['workforce/communication-channels.mdx', 'guides/connect-tools-and-channels.mdx']) jobs.push({ page, source: 'snippets/channel-setup-cards.mdx', component: 'ChannelSetupCards' });
for (const job of jobs) {
  const path = join(root, job.page);
  const original = await readFile(path, 'utf8');
  const source = (await readFile(join(root, job.source), 'utf8')).trim()
    .replace('<figure ', '<div ').replace('</figure>', '</div>')
    .replace('<figcaption aria-hidden="true">', '<span className="channel-hero-caption" aria-hidden="true">')
    .replace('</figcaption>', '</span>').replaceAll('<img ', '<img noZoom ');
  const generated = `${start}\n${source}\n${end}`;
  let next = original;
  if (original.includes(start)) {
    assert.equal(original.split(start).length, 2, `Repeated generated block: ${job.page}`);
    const from = original.indexOf(start);
    const to = original.indexOf(end, from);
    assert(to !== -1, `Unclosed generated block: ${job.page}`);
    next = original.slice(0, from) + generated + original.slice(to + end.length);
  } else {
    const call = `<${job.component} />`;
    assert.equal(original.split(call).length, 2, `Missing or repeated component: ${job.page}`);
    next = next.replace(`import ${job.component} from "/${job.source}";\n\n`, '').replace(call, generated);
  }
  if (next !== original) {
    assert(write, `Stale channel artwork: ${job.page}. Run node scripts/sync-channel-branding.mjs --write`);
    await writeFile(path, next);
  }
}
console.log(`${write ? 'Synchronized' : 'Verified'} shared channel artwork and logo cards on ${jobs.length} pages.`);
